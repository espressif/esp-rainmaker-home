/**
 * Sync `.env.web` → `public/firebase-messaging-sw.js`
 *
 * Browsers reject blob: URLs for service worker registration, so the web FCM
 * client must load a same-origin static worker with Firebase config baked in.
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..", "..", "..");
const ENV_WEB = path.join(ROOT, ".env.web");
const OUTPUT = path.join(ROOT, "public/firebase-messaging-sw.js");
const FIREBASE_JS_COMPAT_VERSION = "12.17.1";
const DEFAULT_TITLE = "ESP RainMaker Home";

/**
 * Parses KEY=VALUE lines from an env file.
 * @param {string} filePath - Env file path
 * @returns {Record<string, string>}
 */
function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }
  const env = {};
  for (const line of fs.readFileSync(filePath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }
    const eq = trimmed.indexOf("=");
    if (eq <= 0) {
      continue;
    }
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

/**
 * Reads public Firebase web config from `.env.web` and process env.
 * @returns {{ apiKey: string, projectId: string, messagingSenderId: string, appId: string }}
 */
function readFirebaseWebConfig() {
  if (!fs.existsSync(ENV_WEB)) {
    console.warn(
      `WARN: ${path.relative(ROOT, ENV_WEB)} not found; web push will be disabled. ` +
        "Copy .env.web.example to .env.web and fill in the Firebase web config."
    );
  }
  const webEnv = parseEnvFile(ENV_WEB);
  return {
    apiKey:
      webEnv.FIREBASE_WEB_API_KEY || process.env.FIREBASE_WEB_API_KEY || "",
    projectId:
      webEnv.FIREBASE_WEB_PROJECT_ID ||
      process.env.FIREBASE_WEB_PROJECT_ID ||
      "",
    messagingSenderId:
      webEnv.FIREBASE_WEB_MESSAGING_SENDER_ID ||
      process.env.FIREBASE_WEB_MESSAGING_SENDER_ID ||
      "",
    appId:
      webEnv.FIREBASE_WEB_APP_ID || process.env.FIREBASE_WEB_APP_ID || "",
  };
}

/**
 * Builds the Firebase Messaging service worker source.
 * @param {{ apiKey: string, projectId: string, messagingSenderId: string, appId: string }} config
 * @returns {string}
 */
function buildServiceWorkerSource(config) {
  const appConfig = {
    apiKey: config.apiKey,
    projectId: config.projectId,
    messagingSenderId: config.messagingSenderId,
    appId: config.appId,
  };

  return `/* SPDX-FileCopyrightText: 2026 Espressif Systems (Shanghai) CO LTD */
/* SPDX-License-Identifier: Apache-2.0 */
/* Generated by deployment/web/scripts/sync-firebase-messaging-sw.js — do not edit manually. */
self.addEventListener("install", (event) => event.waitUntil(self.skipWaiting()));
self.addEventListener("activate", (event) => event.waitUntil(self.clients.claim()));
importScripts("https://www.gstatic.com/firebasejs/${FIREBASE_JS_COMPAT_VERSION}/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/${FIREBASE_JS_COMPAT_VERSION}/firebase-messaging-compat.js");
firebase.initializeApp(${JSON.stringify(appConfig)});
const messaging = firebase.messaging();
const DEFAULT_TITLE = ${JSON.stringify(DEFAULT_TITLE)};
const KEY_EVENT_DATA_PAYLOAD = "event_data_payload";
const KEY_EVENT_DATA = "event_data";
const KEY_TITLE = "title";
const KEY_BODY = "body";

/**
 * Resolves title/body for RainMaker and Firebase Console test payloads.
 * @param {Record<string, string>} data
 * @param {object | undefined} notification
 */
function resolveNotificationContent(data, notification) {
  const title =
    notification?.title || data[KEY_TITLE] || data.title || DEFAULT_TITLE;
  const body = notification?.body || data[KEY_BODY] || data.body || "";
  return { title, body };
}

messaging.onBackgroundMessage((payload) => {
  const data = payload.data || {};
  const notification = payload.notification || {};
  const { title, body } = resolveNotificationContent(data, notification);
  return self.registration.showNotification(title, {
    body,
    data,
    icon: "/favicon.ico",
  });
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  event.waitUntil(
    clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then((clientList) => {
        for (const client of clientList) {
          if ("focus" in client) {
            return client.focus();
          }
        }
        if (clients.openWindow) {
          return clients.openWindow("/");
        }
        return undefined;
      }),
  );
});
`;
}

/**
 * Writes the generated service worker when Firebase web config is complete.
 */
function main() {
  const config = readFirebaseWebConfig();
  const complete =
    config.apiKey &&
    config.projectId &&
    config.messagingSenderId &&
    config.appId;

  if (!complete) {
    console.warn(
      "[sync-firebase-messaging-sw] Missing FIREBASE_WEB_* config in .env.web — writing minimal fallback SW.",
    );
    fs.writeFileSync(
      OUTPUT,
      `/* SPDX-FileCopyrightText: 2026 Espressif Systems (Shanghai) CO LTD */
/* SPDX-License-Identifier: Apache-2.0 */
/* Fallback SW — run deployment/web/scripts/sync-firebase-messaging-sw.js after setting .env.web */
self.addEventListener("install", (event) => event.waitUntil(self.skipWaiting()));
self.addEventListener("activate", (event) =>
  event.waitUntil(self.clients.claim()),
);
`,
      "utf8",
    );
    return;
  }

  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, buildServiceWorkerSource(config), "utf8");
  console.log(
    `[sync-firebase-messaging-sw] Wrote ${path.relative(ROOT, OUTPUT)} for project ${config.projectId}`,
  );
}

main();
